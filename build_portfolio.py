END = "/* ===== DATA BLOCK END ===================================================== */"

# Order matters only for readability of the generated file.
CONSTS = ["ANCHOR", "CAPACITY", "TRENDS", "IMPACTS", "RISK_FLAGS", "STATUS_LOG",
          "STATUS_HISTORY", "USE_CASES"]

